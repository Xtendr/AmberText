// Browser keyboard/name/focus regressions. This does not replace NVDA/VoiceOver.
import { createRequire } from "node:module";
import assert from "node:assert/strict";
const { chromium } = createRequire(import.meta.url)("playwright-core");
const url = process.env.AMBERTEXT_TEST_URL || "http://127.0.0.1:1426";
const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
  const context = await browser.newContext();
  await context.route("**/*", route => {
    const target = new URL(route.request().url());
    return target.origin === new URL(url).origin || !/^https?:$/.test(target.protocol) ? route.continue() : route.abort();
  });
  const page = await context.newPage();
  if (process.env.AMBERTEXT_TEST_REDUCED_MOTION === "1") await page.emulateMedia({reducedMotion:"reduce"});
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(url);
  await page.waitForSelector(".cm-content");
  const tree = page.getByRole("tree", { name: "Files", exact: true });
  const stops = tree.locator('[role="treeitem"][tabindex="0"]');
  await stops.waitFor();
  assert.equal(await stops.count(), 1, "Tree must have one tab stop");
  await stops.focus();
  const focusedPath = () => page.evaluate(() => document.activeElement?.getAttribute("data-tree-path"));
  const first = await focusedPath();
  await page.keyboard.press("ArrowRight");
  assert.equal(await tree.getByRole("treeitem").first().getAttribute("aria-expanded"), "true");
  await page.keyboard.press("ArrowRight");
  assert.notEqual(await focusedPath(), first, "Right arrow must enter expanded folder");
  assert.equal(await page.evaluate(() => document.activeElement.getAttribute("aria-level")), "2");
  await page.keyboard.press("ArrowLeft");
  assert.equal(await focusedPath(), first, "Left arrow must return to parent");
  await page.keyboard.press("ArrowLeft");
  assert.equal(await tree.getByRole("treeitem").first().getAttribute("aria-expanded"), "false");
  await page.keyboard.press("End");
  assert.notEqual(await focusedPath(), first);
  await page.keyboard.press("Home");
  assert.equal(await focusedPath(), first);
  await page.keyboard.press("Shift+F10");
  const menu = page.getByRole("menu", { name: "Actions", exact: true });
  await menu.waitFor();
  await page.keyboard.press("ArrowDown");
  await page.waitForFunction(() => document.querySelector('[role="menu"]')?.getAttribute("aria-activedescendant"));
  const activeAction = await menu.getAttribute("aria-activedescendant");
  assert.ok(activeAction && await page.locator(`#${activeAction}`).count(), "Menu active action must be announced");
  await page.keyboard.press("Escape");
  assert.equal(await focusedPath(), first, "Context menu must return focus");
  await page.keyboard.press("F2");
  const rename = page.getByRole("textbox", { name: "File or folder name" });
  await rename.waitFor();
  await page.keyboard.press("Escape");
  await page.waitForFunction(path => document.activeElement?.getAttribute("data-tree-path") === path, first);
  await page.keyboard.press("F2");
  await rename.fill("Journal renamed");
  await page.keyboard.press("Enter");
  await page.waitForFunction(() => document.activeElement?.getAttribute("data-tree-path")?.endsWith("/Journal renamed"));
  await page.keyboard.press("End");
  await page.keyboard.press("Enter");
  // Owner rule: opening a document with text keeps the rendered page; the writer clicks in to edit.
  await page.waitForFunction(() => document.querySelector('[role="tab"][aria-selected="true"]')?.textContent?.includes("Welcome"));
  await page.locator(".cm-content").click();
  await page.waitForFunction(() => document.activeElement?.classList.contains("cm-content"));
  await page.keyboard.press("Control+f");
  const find = page.getByRole("textbox", { name: "Find in document" });
  await find.waitFor();
  await find.fill("welcome");
  const matchCase = page.getByRole("button", { name: "Match case", exact: true });
  assert.equal(await matchCase.getAttribute("aria-pressed"), "false");
  await matchCase.click();
  assert.equal(await matchCase.getAttribute("aria-pressed"), "true");
  const unnamed = await page.locator(".find button").evaluateAll(buttons => buttons.filter(button => !(button.getAttribute("aria-label") || button.textContent.trim())).length);
  assert.equal(unnamed, 0, "Find has unnamed buttons");
  await page.getByRole("button", { name: "Show replace" }).click();
  await page.getByRole("textbox", { name: "Replace with" }).waitFor();
  await find.focus();
  await page.evaluate(async () => {
    const a = await import("/src/state/actions.ts");
    void a.ask({ title: "Fixture name", message: "Disposable dialog focus check", input: { value: "", placeholder: "Name" }, actions: [{ id: "cancel", label: "Cancel" }, { id: "ok", label: "Save", kind: "primary" }] });
  });
  const dialog = page.getByRole("alertdialog", { name: "Fixture name" });
  await dialog.waitFor();
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Name");
  assert.equal(await dialog.getAttribute("aria-describedby"), "dialog-message");
  await page.keyboard.press("Tab");
  assert.equal(await page.evaluate(() => document.activeElement.textContent), "Cancel", "Trap must skip disabled primary action");
  await page.keyboard.press("Escape");
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Find in document");
  await page.evaluate(async () => (await import("/src/state/store.ts")).setState({ palette: "commands" }));
  const combo = page.getByRole("combobox", { name: "Search commands" });
  await combo.waitFor();
  await combo.focus();
  const before = await combo.getAttribute("aria-activedescendant");
  await page.keyboard.press("ArrowDown");
  assert.notEqual(await combo.getAttribute("aria-activedescendant"), before);
  await page.keyboard.press("Tab");
  assert.equal(await combo.evaluate(el => el === document.activeElement), true, "Palette focus must stay in modal");
  await page.keyboard.press("Escape");
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Find in document");
  await page.getByRole("button", { name: "Close find" }).click();
  await page.waitForFunction(() => document.activeElement?.classList.contains("cm-content"));
  const tabs = page.getByRole("tablist", { name: "Open documents" });
  await tabs.getByRole("tab", { selected: true }).focus();
  const priorTab = await tabs.getByRole("tab", { selected: true }).getAttribute("aria-label");
  await page.keyboard.press("Home");
  await page.keyboard.press("End");
  await page.waitForFunction(() => document.activeElement?.getAttribute("role") === "tab" && document.activeElement.getAttribute("aria-selected") === "true");
  assert.equal(await tabs.getByRole("tab", { selected: true }).getAttribute("aria-label"), priorTab);
  const modes = page.getByRole("radiogroup", { name: "View mode" });
  await modes.getByRole("radio", { name: "Write", exact: true }).focus();
  await page.keyboard.press("ArrowRight");
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Split" && document.activeElement.getAttribute("aria-checked") === "true");
  await page.keyboard.press("ArrowRight");
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Read" && document.activeElement.getAttribute("aria-checked") === "true");
  await page.keyboard.press("Home");
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Write" && document.activeElement.getAttribute("aria-checked") === "true");
  await page.evaluate(async () => (await import("/src/editor/bridge.ts")).bridge.view.dispatch({ selection: { anchor: 0 } }));
  await page.keyboard.press("Control+j");
  const aiInput = page.getByRole("combobox", { name: "Ask AI about the document" });
  await aiInput.waitFor();
  await aiInput.focus();
  const aiBefore = await aiInput.getAttribute("aria-activedescendant");
  await page.keyboard.press("ArrowDown");
  await page.waitForFunction(before => {
    const input = document.querySelector('[aria-controls="ai-menu-options"]');
    return input?.getAttribute("aria-activedescendant") && input.getAttribute("aria-activedescendant") !== before;
  }, aiBefore);
  await page.keyboard.press("Escape");
  await page.waitForFunction(() => document.activeElement?.classList.contains("cm-content"));
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  const settings = page.getByRole("dialog", { name: "Settings", exact: true });
  await settings.waitFor();
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Close settings");
  await page.keyboard.press("Shift+Tab");
  assert.equal(await settings.evaluate(el => el.contains(document.activeElement)), true);
  await settings.getByRole("button", { name: "Shortcuts", exact: true }).click();
  await settings.getByRole("textbox", { name: "Filter keyboard shortcuts" }).waitFor();
  await page.keyboard.press("Escape");
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Settings");
  await page.emulateMedia({ reducedMotion: "reduce", forcedColors: "active" });
  await page.keyboard.press("Tab");
  const focusOutline = await page.evaluate(() => ({ style: getComputedStyle(document.activeElement).outlineStyle, width: getComputedStyle(document.activeElement).outlineWidth }));
  assert.deepEqual(focusOutline, { style: "solid", width: "2px" }, "Forced colors must retain a visible focus outline");
  const scrolling = await page.evaluate(async () => {
    const { bridge } = await import("/src/editor/bridge.ts");
    const a = await import("/src/state/actions.ts");
    let behavior;
    const scroll = bridge.view.scrollDOM.scrollTo;
    bridge.view.scrollDOM.scrollTo = options => { behavior = options.behavior; };
    try { a.scrollToHeading(0); } finally { bridge.view.scrollDOM.scrollTo = scroll; }
    return behavior;
  });
  assert.equal(scrolling, "auto", "Reduced motion must avoid smooth heading scrolling");
  if (process.env.AMBERTEXT_SCREENSHOT_PATH) await page.screenshot({ path: process.env.AMBERTEXT_SCREENSHOT_PATH });
  assert.deepEqual(errors, [], "Browser runtime errors");
  console.log(JSON.stringify({ surface: "isolated browser", passed: ["tree roving/arrows/parent/end/home", "keyboard context menu/focus return", "rename cancellation/success focus", "keyboard file opening", "Find names/pressed state", "dialog naming/trap/focus return", "palette active option/trap/focus return", "document tabs keyboard selection", "settings focus/trap/return/input name", "forced-color focus outline", "reduced-motion heading scrolling"], manualPending: ["NVDA", "VoiceOver", "native installed profiles", "physical IME", "native 200% zoom", "full contrast matrix"] }));
} finally { await browser.close(); }
